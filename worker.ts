// Production Worker entry (wrangler.jsonc "main"). Wraps the Worker OpenNext
// generates, so one route can be answered before the Next server is loaded.
//
// /api/hns/* is the console's proxy to hostnsoft-api — every panel read goes
// through it. Handled by OpenNext, each call paid for booting the Next server
// (~150ms median Worker CPU in the dashboard) just to forward one request.
// Answering it here runs the same forwardRequest the Next route uses
// (app/lib/hnsForward.ts), so behaviour is identical and only the start-up is
// skipped. Everything else goes to OpenNext untouched.
//
// Only in production: `next dev` never runs this file and serves the route.

// @ts-ignore `.open-next/worker.js` is generated by `opennextjs-cloudflare build`
import { default as openNext } from "./.open-next/worker.js";
import { FORWARDED_METHODS, forwardRequest } from "./app/lib/hnsForward";

const PREFIX = "/api/hns/";

export default {
  async fetch(request: Request, env: CloudflareEnv, ctx: unknown): Promise<Response> {
    const url = new URL(request.url);
    if (
      url.pathname.startsWith(PREFIX) &&
      FORWARDED_METHODS.has(request.method.toUpperCase()) &&
      // www is redirected to the apex by next.config.mjs; let Next keep doing that.
      url.hostname !== "www.embarko.ai"
    ) {
      // Decoded the way Next hands the route its [...path] params.
      const segments = url.pathname
        .slice(PREFIX.length)
        .split("/")
        .filter(Boolean)
        .map((s) => {
          try {
            return decodeURIComponent(s);
          } catch {
            return s;
          }
        });
      if (segments.length > 0) {
        return forwardRequest(request, env.HOSTNSOFT_API_URL ?? "http://localhost:4100", segments);
      }
    }
    return openNext.fetch(request, env, ctx);
  },
};

