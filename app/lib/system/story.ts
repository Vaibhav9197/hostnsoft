/* The story layer of the Live PRD — written by people, checked against code.
 *
 * Embarko is three repos, and the stories run through all of them:
 *
 *   hostnsoft          the website, the panel, the admin pages (this repo)
 *   hostnsoft-api      accounts, apps, tokens, domains, billing, Showcase  (@api)
 *   hostnsoft-deploy   builds the apps and keeps them running              (@deploy)
 *
 * Three things live here: the parts of the product (AREAS), what passes
 * between them (FLOWS) and the user stories (JOURNEYS). Every `refs` entry is
 * an ID from the scanned facts (app/lib/system/facts.generated.json):
 *
 *   page:<route>             a screen
 *   api:<route>              an endpoint here;  api:@api/<route>, api:@deploy/<route> in the others
 *   lib:<file>               a module here;     lib:@api/<file>, lib:@deploy/<file> in the others
 *   table:store:<name>       site database      table:api:<Model>, table:deploy:<name>
 *   ext:<name>               an outside service
 *
 * A ref ending in `/*` covers everything under that path. A ref that stops
 * existing shows as stale on /admin/system and fails `npm run prd:check`.
 *
 * No imports, so plain scripts can load it. After editing, run `npm run prd`.
 *
 * Written from the code, not from users' words: every "goal" is an
 * assumption until someone who uses Embarko confirms it. An automatic step
 * with no `failure` is an open question — leave it empty rather than guess.
 */

export type Lane = "people" | "screens" | "engine" | "background" | "data" | "outside";
export type Judge = "human" | "ai" | "rule" | "mixed";
export type Actor = "user" | "system" | "ai" | "rule" | "outside";

export type Area = {
  id: string;
  /** Two to four words. */
  name: string;
  lane: Lane;
  /** One sentence, no jargon. */
  plain: string;
  /** How it really works. */
  detail?: string;
  judge?: Judge;
  refs: string[];
};

export type Flow = { from: string; to: string; label: string };

export type Step = {
  id: string;
  title: string;
  plain: string;
  actor: Actor;
  choices?: string[];
  /** Each one written exactly as "Condition → result." */
  failure?: string[];
  areas: string[];
  refs: string[];
};

export type Journey = {
  id: string;
  /** One to three words in Title Case — the heading everywhere. */
  short: string;
  /** The story as a short sentence. */
  name: string;
  who: string;
  /** Completes "wants to …". */
  goal: string;
  outcome: string;
  steps: Step[];
};

