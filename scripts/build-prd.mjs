// Writes docs/prd/ — the Live PRD as markdown, for AI agents — from the same
// model the /admin/system page shows (loadSystemMap and storyHistories in
// app/lib/system/). Refreshes the facts first.
//
//   npm run prd         regenerate
//   npm run prd:check   exit 1 if docs/prd/ is behind the code or the story
//
// Files carry no timestamps or commit IDs of their own, so the check fails
// only on a real change.

import fs from "node:fs";
import path from "node:path";
import { register } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

import { buildFacts, FACTS_FILE } from "./build-system-map.mjs";

register("./ts-loader.mjs", import.meta.url);

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "docs/prd");
const APP_NAME = "Embarko";
const PAGE = "/admin/system";
const AGENT_FILE = "CLAUDE.md";
const HEADER = "<!-- Generated by scripts/build-prd.mjs from app/lib/system/story.ts and the code. Do not edit by hand — run npm run prd. -->";

const check = process.argv.includes("--check");

const sys = await import(pathToFileURL(path.join(ROOT, "app/lib/system/map.ts")).href);
const { storyHistories } = await import(pathToFileURL(path.join(ROOT, "app/lib/system/history.ts")).href);

/* Refresh the facts the page reads too, so both outputs agree. */
const facts = buildFacts();
if (!check) {
  const file = path.join(ROOT, FACTS_FILE);
  const json = JSON.stringify(facts, null, 2) + "\n";
  const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (old !== json) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, json);
  }
}
const history = JSON.parse(fs.readFileSync(path.join(ROOT, "app/lib/system/history.generated.json"), "utf8"));
const map = sys.loadSystemMap(facts);
const versions = storyHistories(map, history);

// --- helpers -------------------------------------------------------------------

const ACTOR = { user: "Person", system: "System", ai: "AI", rule: "Rule", outside: "Outside service" };
const JUDGE = { human: "a person", ai: "AI", rule: "a fixed rule", mixed: "a mix of people, AI and rules" };
const areaById = new Map(map.areas.map((a) => [a.id, a]));
const laneName = new Map(sys.LANES.map((l) => [l.id, l.name]));
const nameOf = (id) => {
  const f = map.byId.get(id);
  if (!f) return id;
  if (f.kind === "table" || f.kind === "service") return f.name;
  return f.route ?? f.file;
};
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const code = (s) => "`" + s + "`";
const day = (iso) => new Date(iso).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "Asia/Kolkata" });
const storyLink = (j, from = "root") => `[${j.short}](${from === "root" ? "stories/" : ""}${j.id}.md)`;
const tableName = (id) => map.byId.get(id)?.name ?? id.split(":").pop();

/* Mermaid labels: no quotes, brackets, parentheses, braces or entity starters;
   apostrophes become ’ so "doesn't" survives. */
const label = (s) =>
  String(s)
    .replace(/'/g, "\u2019")
    .replace(/["`[\](){}<>#;|]/g, "")
    .replace(/\s+/g, " ")
    .trim();

function flowchart(j) {
  const L = ["```mermaid", "flowchart TD"];
  L.push(`  start([${label(`${j.who} wants to ${j.goal}`)}])`);
  /* The open ends the next node joins onto, each with its arrow label. */
  let prev = [{ id: "start", text: "" }];
  const join = (to) => prev.forEach((p) => L.push(`  ${p.id} -->${p.text ? `|${p.text}|` : ""} ${to}`));
  j.steps.forEach((s, i) => {
    const id = `s${i + 1}`;
    L.push(`  ${id}["${label(`${i + 1}. ${s.title}`)}<br/>${label(ACTOR[s.actor])}"]`);
    join(id);
    prev = [{ id, text: "" }];
    if (s.choices?.length) {
      const d = `${id}c`;
      L.push(`  ${d}{${label(s.actor === "user" ? "They choose" : "Which way?")}}`);
      join(d);
      prev = s.choices.map((c, k) => {
        const cid = `${d}${k + 1}`;
        L.push(`  ${cid}([${label(c)}])`);
        L.push(`  ${d} --> ${cid}`);
        return { id: cid, text: "" };
      });
    }
    if (s.failure?.length) {
      const d = `${id}f`;
      L.push(`  ${d}{Did it work?}`);
      join(d);
      s.failure.forEach((f, k) => {
        const { condition, result } = sys.splitFailure(f);
        const fid = `${d}${k + 1}`;
        L.push(`  ${fid}["${label(`If ${condition}`)}<br/>${label(`→ ${result}`)}"]:::fail`);
        L.push(`  ${d} -.->|no| ${fid}`);
      });
      prev = [{ id: d, text: "yes" }];
    }
  });
  L.push(`  done([${label(j.outcome)}])`);
  join("done");
  L.push("  classDef fail fill:#fde8e8,stroke:#dc2626,color:#7f1d1d");
  L.push("```");
  return L.join("\n");
}

function systemMapChart() {
  const L = ["```mermaid", "flowchart LR"];
  for (const lane of sys.LANES) {
    const areas = map.areas.filter((a) => a.lane === lane.id);
    if (!areas.length) continue;
    L.push(`  subgraph ${lane.id}[${label(lane.name)}]`);
    for (const a of areas) L.push(`    ${a.id.replace(/[^\w]/g, "_")}["${label(a.name)}"]`);
    L.push("  end");
  }
  for (const f of map.flows) L.push(`  ${f.from.replace(/[^\w]/g, "_")} -->|${label(f.label)}| ${f.to.replace(/[^\w]/g, "_")}`);
  L.push("```");
  return L.join("\n");
}

const storiesUsingArea = (areaId) => map.journeys.filter((j) => j.steps.some((s) => s.areas.includes(areaId)));
const storiesUsingTable = (tableId) =>
  map.journeys.filter((j) => {
    const t = sys.journeyTables(map, j);
    return t.kept.includes(tableId) || t.lookedUp.includes(tableId);
  });

// --- README --------------------------------------------------------------------

function readme() {
  const L = [`# ${APP_NAME} — Live PRD`, "", HEADER, ""];
  L.push("## Read this first", "");
  L.push(
    `${APP_NAME} hosts apps that people's AI agents build. It is three repos, and this PRD covers all of them:`,
    "",
    ...map.facts.repos.map((r) => `- **${r.name}**${r.alias ? ` (\`${r.alias}\`)` : " (this repo)"} — ${r.plain}.${r.available ? "" : " _Read from the saved snapshot; the repo wasn't next to this one._"}`),
    "",
    `This folder is **generated** from the code of all three and from the story file \`app/lib/system/story.ts\`. It mirrors the admin page at \`${PAGE}\`. Each story below has its own file with the exact screens, endpoints, modules and tables for every step, by ID. The sibling repos are read from \`../hostnsoft-api\` and \`../hostnsoft-deploy\`; their part of the scan is saved in \`app/lib/system/facts.repos.json\`.`,
    "",
    "IDs: `page:<route>` a screen · `api:<route>` an endpoint here, `api:@api/<route>` and `api:@deploy/<route>` in the others · `lib:<file without extension>` a module (`lib:@api/…`, `lib:@deploy/…`) · `table:store:<name>` site database, `table:api:<Model>` API database, `table:deploy:<name>` traffic database · `ext:<name>` an outside service · `<story>/<step>` a step.",
    "",
  );
  L.push("## Purpose", "", `> ${sys.proposedPurpose(map, APP_NAME)}`, "", "_Proposal, built from the stories — not confirmed by a person yet._", "");
  L.push("## Who it is for", "");
  for (const a of map.areas.filter((x) => x.lane === "people")) L.push(`- **${a.name}** — ${a.plain}`);
  L.push("");
  L.push("## Stories", "", "| # | Story | Who | Wants to | Steps | Can go wrong |", "|---|---|---|---|---|---|");
  map.journeys.forEach((j, i) => {
    const fails = j.steps.filter((s) => s.failure?.length).length;
    L.push(`| ${i + 1} | ${storyLink(j)} — ${cell(j.name)} | ${cell(j.who)} | ${cell(j.goal)} | ${j.steps.length} | ${fails} |`);
  });
  L.push("");
  L.push("## The rest of the picture", "");
  L.push("- [system-map.md](system-map.md) — every part of the product, what it does, and what passes between parts.");
  L.push("- [tables.md](tables.md) — every table in the site database, what it means, and who writes it.");
  L.push("");
  const f = map.facts;
  L.push("## How it is made", "");
  for (const r of f.repos) {
    const n = (xs) => xs.filter((x) => x.repo === r.id).length;
    L.push(`- **${r.name}:** ${n(f.screens) ? `${n(f.screens)} screens · ` : ""}${n(f.endpoints)} endpoints · ${n(f.modules)} modules · ${n(f.tables)} tables`);
  }
  L.push("- **Stack:** hostnsoft is Next.js on Cloudflare Workers (OpenNext). hostnsoft-api is TypeScript Express with Prisma on SQLite and Redis. hostnsoft-deploy is Node Express, building with Railpack and running apps as Nomad jobs behind Traefik.");
  for (const s of f.stores) L.push(`- **Store:** ${s.name} — ${s.engine} (\`${s.binding}\`)${s.rows ? ", rows readable from the admin page" : ", structure only from the admin page"}.`);
  L.push(`- **Outside services:** ${f.services.map((s) => `${s.name} (${s.type})`).join(", ")}`);
  L.push(`- **Agent instructions:** [${AGENT_FILE}](../../${AGENT_FILE})`);
  L.push("");
  L.push("## Not explored yet", "");
  const idle = sys.areasInNoStory(map);
  const unused = sys.codeInNoStory(map);
  const tables = sys.tablesInNoStory(map);
  L.push(`- **Parts in no story:** ${idle.length ? idle.map((a) => `${a.name} (${code(a.id)})`).join(", ") : "none"}`);
  L.push(`- **Endpoints in no story:** ${f.endpoints.length - unused.endpoints.length} of ${f.endpoints.length} are covered. Not covered: ${unused.endpoints.map(code).join(", ") || "none"}`);
  L.push(`- **Modules in no story:** ${f.modules.length - unused.modules.length} of ${f.modules.length} are named by a step; the rest are reached only through their part (see system-map.md).`);
  L.push(`- **Tables in no story:** ${tables.length ? tables.map((t) => code(tableName(t))).join(", ") : "none"}`);
  if (map.missing.length) L.push(`- **Stale refs:** ${map.missing.map((m) => `${code(m.ref)} (${m.where})`).join(", ")}`);
  if (map.unplaced.length) L.push(`- **Code in no part:** ${map.unplaced.map(code).join(", ")}`);
  L.push("- **Next steps, out of scope for now:** editing stories from the page, real-case replay, expected-vs-actual evidence, permissions per step, a glossary, rules that must always hold, status flows.");
  L.push("");
  L.push("## Keeping it current", "");
  L.push("1. When a change alters a story, a step, a table or code a story names, edit `app/lib/system/story.ts`.");
  L.push("2. Run `npm run prd` to regenerate this folder.");
  L.push("3. `npm run prd:check` fails while this folder is behind the code or the story.");
  L.push("4. Versions come from git through `scripts/build-system-history.mjs`, which writes the committed `app/lib/system/history.generated.json`.");
  L.push("");
  return L.join("\n");
}

// --- stories -------------------------------------------------------------------

function story(j, i) {
  const L = [`# Story ${i + 1}: ${j.short}`, "", HEADER, ""];
  const fails = j.steps.filter((s) => s.failure?.length).length;
  const ai = j.steps.filter((s) => s.actor === "ai").length;
  const v = versions[j.id] ?? [];
  L.push(`- **ID:** ${code(j.id)} (steps are ${code(`${j.id}/<step>`)})`);
  L.push(`- **Story:** ${j.name}`);
  L.push(`- **Who:** ${j.who}`);
  L.push(`- **Wants to:** ${j.goal}`);
  L.push(`- **Ends with:** ${j.outcome}`);
  L.push(`- **Steps:** ${j.steps.length} · ${ai} by AI · ${fails} can go wrong`);
  if (v[0]) L.push(`- **Last change to its code:** v${v[0].n}, ${day(v[0].date)} — ${v[0].subject}`);
  L.push("", "[← All stories](../README.md)", "");

  L.push("## Steps", "", "| # | Step ID | Step | Who acts | What happens |", "|---|---|---|---|---|");
  j.steps.forEach((s, k) => L.push(`| ${k + 1} | ${code(`${j.id}/${s.id}`)} | ${cell(s.title)} | ${ACTOR[s.actor]} | ${cell(s.plain)} |`));
  L.push("", "## Flow", "", flowchart(j), "");

  L.push("## Each step in detail", "");
  j.steps.forEach((s, k) => {
    L.push(`### ${k + 1}. ${s.title}`, "");
    L.push(`- **ID:** ${code(`${j.id}/${s.id}`)}`);
    L.push(`- **Who acts:** ${ACTOR[s.actor]}`);
    L.push(`- **What happens:** ${s.plain}`);
    if (s.choices?.length) L.push(`- **Choices:** ${s.choices.join(" · ")}`);
    if (s.failure?.length) {
      L.push("- **If it goes wrong:**");
      for (const f of s.failure) {
        const { condition, result } = sys.splitFailure(f);
        L.push(`  - If ${condition} → ${result}`);
      }
    } else if (s.actor !== "user") {
      L.push("- **If it goes wrong:** not written down yet — open question.");
    }
    L.push(`- **Parts:** ${s.areas.map((a) => `${areaById.get(a)?.name ?? a} (${code(a)})`).join(", ") || "none"}`);
    const t = sys.stepTables(map, s);
    if (t.kept.length) L.push(`- **Keeps:** ${t.kept.map((x) => code(tableName(x))).join(", ")}`);
    if (t.lookedUp.length) L.push(`- **Looks up:** ${t.lookedUp.map((x) => code(tableName(x))).join(", ")}`);
    const refs = sys.stepRefs(map, s).filter((r) => !r.startsWith("table:") && !r.startsWith("ext:"));
    if (refs.length) L.push(`- **Code:** ${refs.map((r) => `${code(r)}${map.byId.get(r)?.file ? ` → ${code(map.byId.get(r).file)}` : ""}`).join(", ")}`);
    const svc = sys.stepServices(map, s);
    if (svc.length) L.push(`- **Outside services:** ${svc.map((x) => nameOf(x)).join(", ")}`);
    L.push("");
  });

  L.push("## Parts involved", "", "| Part | Lane | What it does |", "|---|---|---|");
  for (const id of sys.journeyAreas(j)) {
    const a = areaById.get(id);
    if (a) L.push(`| ${a.name} (${code(a.id)}) | ${laneName.get(a.lane)} | ${cell(a.plain)} |`);
  }
  L.push("", "See [system-map.md](../system-map.md) for how the parts connect.", "");

  const t = sys.journeyTables(map, j);
  L.push("## Tables", "");
  if (!t.kept.length && !t.lookedUp.length) L.push("This story writes nothing to the site database; its data lives in the Embarko API.");
  for (const x of t.kept) L.push(`- **Keeps** ${code(tableName(x))}${map.byId.get(x)?.note ? ` — ${map.byId.get(x).note}` : ""}`);
  for (const x of t.lookedUp) L.push(`- **Looks up** ${code(tableName(x))}${map.byId.get(x)?.note ? ` — ${map.byId.get(x).note}` : ""}`);
  L.push("", "See [tables.md](../tables.md).", "");

  L.push("## Recent changes", "");
  if (!v.length) L.push("No history for this story's code.");
  else {
    L.push("| Version | Date | Change | Steps changed |", "|---|---|---|---|");
    for (const x of v.slice(0, 5)) {
      L.push(`| v${x.n} (${x.short}) | ${day(x.date)} | ${cell(x.subject)} | ${x.stepsChanged.map((s) => s.step).join(", ") || "—"} |`);
    }
  }
  L.push("");

  L.push("## Open questions", "");
  for (const s of sys.openSteps(j)) L.push(`- Step ${code(`${j.id}/${s.id}`)} (${s.title}) runs on its own but has no failure written down.`);
  for (const m of map.missing.filter((m) => m.where.startsWith(`story ${j.id},`))) L.push(`- Stale ref ${code(m.ref)} in ${m.where}.`);
  L.push("- This story was written from the code; treat \"wants to\" as an assumption until a user confirms it.");
  L.push("");
  return L.join("\n");
}

// --- system map ----------------------------------------------------------------

function systemMap() {
  const L = [`# ${APP_NAME} — System map`, "", HEADER, "", "[← All stories](README.md)", "", systemMapChart(), ""];
  for (const lane of sys.LANES) {
    const areas = map.areas.filter((a) => a.lane === lane.id);
    if (!areas.length) continue;
    L.push(`## ${lane.name} — ${lane.plain}`, "");
    for (const a of areas) {
      L.push(`### ${a.name} (${code(a.id)})`, "");
      L.push(a.plain, "");
      if (a.detail) L.push(`- **How it works:** ${a.detail}`);
      if (a.judge) L.push(`- **Who decides:** ${JUDGE[a.judge]}`);
      const out = map.flows.filter((f) => f.from === a.id);
      const inn = map.flows.filter((f) => f.to === a.id);
      if (out.length) L.push(`- **Passes to:** ${out.map((f) => `${areaById.get(f.to)?.name ?? f.to} (${f.label})`).join(", ")}`);
      if (inn.length) L.push(`- **Receives from:** ${inn.map((f) => `${areaById.get(f.from)?.name ?? f.from} (${f.label})`).join(", ")}`);
      const st = storiesUsingArea(a.id);
      if (st.length) L.push(`- **Stories:** ${st.map((j) => `[${j.short}](stories/${j.id}.md)`).join(", ")}`);
      const files = sys.areaFiles(map, a.id);
      if (files.length) L.push(`- **Code files:** ${files.map(code).join(", ")}`);
      const tables = (map.areaFacts.get(a.id) ?? []).filter((x) => x.startsWith("table:"));
      if (tables.length) L.push(`- **Tables:** ${tables.map((x) => code(tableName(x))).join(", ")}`);
      const services = (map.areaFacts.get(a.id) ?? []).filter((x) => x.startsWith("ext:"));
      if (services.length) L.push(`- **Services:** ${services.map(nameOf).join(", ")}`);
      L.push("");
    }
  }
  return L.join("\n");
}

// --- tables --------------------------------------------------------------------

function tablesDoc() {
  const L = [`# ${APP_NAME} — Tables`, "", HEADER, "", "[← All stories](README.md)", ""];
  L.push(
    "Three stores, all Embarko's own:",
    "",
    ...map.facts.stores.map((s) => `- **${s.name}** — ${s.engine} (\`${s.binding}\`).`),
    "",
    "Declared links come from foreign keys (Prisma `@relation`); the rest are inferred from column names. Owners are MSG91 ids stored as text — there is no user or workspace table.",
    "",
  );
  const shapes = map.facts.tables.map((t) => ({ name: t.name, columns: t.columns, pk: [] }));
  for (const t of map.facts.tables) {
    L.push(`## ${t.name}`, "");
    L.push(`- **Store:** ${map.facts.stores.find((s) => s.id === t.store)?.name ?? t.store} (${code(t.id)})`);
    L.push(`- **Meaning:** ${t.note ?? "No note in the migration."}`);
    const parts = map.factAreas.get(t.id) ?? [];
    L.push(`- **Part:** ${parts.map((a) => `${areaById.get(a)?.name ?? a} (${code(a)})`).join(", ") || "none"}`);
    L.push(`- **Defined in:** ${code(t.migration)}`);
    L.push(`- **Columns:** ${t.columns.map(code).join(", ")}`);
    const declared = map.facts.foreignKeys.filter((k) => k.from.startsWith(`${t.id}.`));
    L.push(`- **Declared links:** ${declared.length ? declared.map((k) => `${k.from} → ${k.to}`).join(", ") : "none"}`);
    const st = storiesUsingTable(t.id);
    L.push(`- **Stories:** ${st.length ? st.map((j) => `[${j.short}](stories/${j.id}.md)`).join(", ") : "none — not explored yet"}`);
    const writers = [...map.facts.endpoints, ...map.facts.modules].filter((x) => x.tablesWritten.includes(t.id)).map((x) => code(x.id));
    const readers = [...map.facts.endpoints, ...map.facts.modules].filter((x) => x.tablesRead.includes(t.id)).map((x) => code(x.id));
    L.push(`- **Written by:** ${writers.join(", ") || "nothing in this repo"}`);
    L.push(`- **Read by:** ${readers.join(", ") || "nothing in this repo"}`);
    L.push("");
  }
  void shapes;
  if (map.facts.externalStores.length === 0) {
    L.push("## External tables", "", "None. This app reads no other database directly; everything else comes from the Embarko API over HTTP.", "");
  }
  return L.join("\n");
}

// --- write / check ------------------------------------------------------------

const files = new Map();
files.set("README.md", readme());
map.journeys.forEach((j, i) => files.set(`stories/${j.id}.md`, story(j, i)));
files.set("system-map.md", systemMap());
files.set("tables.md", tablesDoc());

const existing = new Set();
const walk = (dir, prefix = "") => {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) walk(path.join(dir, e.name), `${prefix}${e.name}/`);
    else if (e.name.endsWith(".md")) existing.add(`${prefix}${e.name}`);
  }
};
walk(OUT);

const stale = [];
for (const [rel, text] of files) {
  const full = path.join(OUT, rel);
  const body = text.trimEnd() + "\n";
  const old = fs.existsSync(full) ? fs.readFileSync(full, "utf8") : null;
  if (old !== body) {
    stale.push(rel);
    if (!check) {
      fs.mkdirSync(path.dirname(full), { recursive: true });
      fs.writeFileSync(full, body);
    }
  }
}
for (const rel of existing) {
  if (rel.startsWith("stories/") && !files.has(rel)) {
    stale.push(`${rel} (removed)`);
    if (!check) fs.rmSync(path.join(OUT, rel));
  }
}

const problems = [
  ...map.missing.map((m) => `stale ref ${m.ref} in ${m.where}`),
  ...map.unplaced.map((id) => `${id} is in no part`),
];

if (check) {
  if (stale.length) {
    console.error(`prd: docs/prd is out of date (${stale.join(", ")}) — run npm run prd`);
    process.exit(1);
  }
  if (problems.length) {
    console.error(`prd: the story needs attention:\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  console.log("prd: up to date");
} else {
  console.log(`prd: ${files.size} files${stale.length ? `, updated ${stale.length}` : ", no change"}`);
  if (problems.length) console.warn(`prd: the story needs attention:\n  ${problems.join("\n  ")}`);
}
